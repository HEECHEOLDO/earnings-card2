def main():
    try:
        s = open(FN, encoding="utf-8").read()
    except OSError:
        print("!! %s 가 없습니다. fincard 폴더에서 실행하세요." % FN)
        sys.exit(1)
    pat = re.compile(r"var MCAP_EMOJI = \{ upjong: .*?, other: '[^']*' \};( // [\w-]+)?", re.S)
    found = pat.findall(s)
    if len(found) != 1:
        print("!! %s 에 이모지 표가 없습니다. patch_mcap_emoji.py 를 먼저 돌리세요." % FN)
        sys.exit(1)
    new = ("var MCAP_EMOJI = { upjong: %s,\n    theme: %s, other: '%s' }; // %s"
           % (json.dumps(UPJONG, ensure_ascii=False), json.dumps(THEME, ensure_ascii=False), OTHER, VER))
    if new in s:
        print("  그대로  %s  이미 고쳐짐" % FN)
        return
    s = pat.sub(lambda m: new, s)
    open(FN, "w", encoding="utf-8").write(s)
    print("  고침    %s  — 이모지 표 새로 (업종 %d · 테마 규칙 %d)" % (FN, len(UPJONG), len(THEME)))


if __name__ == "__main__":
    main()
